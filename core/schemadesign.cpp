QByteArray SchemaDesign::toJson() const
{
    QJsonArray design;
    for (const DesignTable &t : m_tables)
        design << QJsonObject{ { QStringLiteral("table"), tableToJson(t.info) },
                               { QStringLiteral("origin"), t.origin },
                               { QStringLiteral("columnOrigins"), QJsonArray::fromStringList(t.columnOrigins) } };
    const QJsonObject root{
        { QStringLiteral("format"), QStringLiteral("qivot-design") },
        { QStringLiteral("version"), FormatVersion },
        { QStringLiteral("dialect"), m_dialect },
        { QStringLiteral("database"), m_session && m_session->isOpen() ? m_session->displayName() : QString() },
        { QStringLiteral("original"), schemaToJson(m_original) },
        { QStringLiteral("design"), design },
    };
    return QJsonDocument(root).toJson(QJsonDocument::Indented);
}

bool SchemaDesign::fromJson(const QByteArray &json, QString *why)
{
    QJsonParseError parse;
    const QJsonDocument doc = QJsonDocument::fromJson(json, &parse);
    const QJsonObject root = doc.object();
    if (doc.isNull() || root.value(QStringLiteral("format")).toString() != QLatin1String("qivot-design")) {
        if (why)
            *why = doc.isNull() ? parse.errorString() : tr("This isn't a Qivot Studio design.");
        return false;
    }
    if (root.value(QStringLiteral("version")).toInt() > FormatVersion) {
        if (why)
            *why = tr("This design was saved by a newer Qivot Studio.");
        return false;
    }
    QVector<QiTableInfo> original;
    for (const QJsonValue &v : root.value(QStringLiteral("original")).toArray())
        original << tableFromJson(v.toObject());
    QVector<DesignTable> design;
    for (const QJsonValue &v : root.value(QStringLiteral("design")).toArray()) {
        const QJsonObject o = v.toObject();
        DesignTable t;
        t.info = tableFromJson(o.value(QStringLiteral("table")).toObject());
        t.origin = o.value(QStringLiteral("origin")).toString();
        t.columnOrigins = strings(o.value(QStringLiteral("columnOrigins")));
        while (t.columnOrigins.size() < t.info.columns.size())
            t.columnOrigins << QString();
        design << t;
    }
    m_dialect = root.value(QStringLiteral("dialect")).toString(QStringLiteral("sqlite"));
    m_original = original;
    m_tables = design;
    m_undo.clear();
    m_redo.clear();
    return true;
}

bool SchemaDesign::save(const QVariant &fileOrUrl)
{
    QString path = localPath(fileOrUrl);
    if (!path.endsWith(QLatin1String(".qivotdesign")))
        path += QStringLiteral(".qivotdesign");
    QFile file(path);
    if (!file.open(QIODevice::WriteOnly) || file.write(toJson()) < 0) {
        setError(tr("Couldn't save %1: %2").arg(QFileInfo(path).fileName(), file.errorString()));
        return false;
    }
    m_filePath = path;
    setError(QString());
    emit designChanged();
    return true;
}

bool SchemaDesign::load(const QVariant &fileOrUrl)
{
    const QString path = localPath(fileOrUrl);
    QFile file(path);
    if (!file.open(QIODevice::ReadOnly)) {
        setError(tr("Couldn't open %1: %2").arg(QFileInfo(path).fileName(), file.errorString()));
        return false;
    }
    QString why;
    if (!fromJson(file.readAll(), &why)) {
        setError(why);
        return false;
    }
    m_filePath = path;
    m_restored = false;
    // Say so if the database it was designed against has changed since.
    QString note;
    if (m_session && m_session->isOpen()) {
        SchemaDesign now;
        now.reset(m_session->tableInfos(), m_session->dialect());
        if (schemaToJson(now.m_original) != schemaToJson(m_original))
            note = tr("The open database has changed since this design was made; the migration compares "
                      "with the schema saved in the design.");
    }
    setError(note);
    m_loading = true;
    emit designChanged();
    m_loading = false;
    return true;
}

QString SchemaDesign::autosavePath() const
{
    if (!m_session || !m_session->isOpen())
        return QString();
    const QVariantMap s = m_session->connectionSettings();
    const QByteArray key = (s.value(QStringLiteral("type")).toString() + QLatin1Char('|')
                            + s.value(QStringLiteral("path")).toString() + QLatin1Char('|')
                            + s.value(QStringLiteral("host")).toString() + QLatin1Char('|')
                            + s.value(QStringLiteral("port")).toString() + QLatin1Char('|')
                            + s.value(QStringLiteral("database")).toString()).toUtf8();
    const QString dir = QStandardPaths::writableLocation(QStandardPaths::AppDataLocation) + QStringLiteral("/designs");
    return dir + QLatin1Char('/') + QString::fromLatin1(QCryptographicHash::hash(key, QCryptographicHash::Sha1).toHex().left(16))
         + QStringLiteral(".qivotdesign");
}

void SchemaDesign::setAutosaveEnabled(bool on)
{
    if (on == m_autosave)
        return;
    m_autosave = on;
    emit autosaveChanged();
}

void SchemaDesign::autosave()
{
    if (m_loading || !m_autosave)
        return;
    const QString path = autosavePath();
    if (path.isEmpty())
        return;
    if (Migration::changes(m_original, m_tables).isEmpty()) {
        QFile::remove(path);                // nothing worth keeping
        return;
    }
    QDir().mkpath(QFileInfo(path).absolutePath());
    QFile file(path);
    if (file.open(QIODevice::WriteOnly))
        file.write(toJson());
}

bool SchemaDesign::restoreAutosave()
{
    const QString path = m_autosave ? autosavePath() : QString();
    QFile file(path);
    if (path.isEmpty() || !file.open(QIODevice::ReadOnly))
        return false;
    SchemaDesign saved;
    if (!saved.fromJson(file.readAll()))
        return false;
    // Only if it was made against the database as it is now.
    if (schemaToJson(saved.m_original) != schemaToJson(m_original) || saved.m_dialect != m_dialect)
        return false;
    m_tables = saved.m_tables;
    m_restored = true;
    return true;
}

int SchemaDesign::errorCount() const
{
    int n = 0;
    for (const QVariant &p : m_problems)
        n += p.toMap().value(QStringLiteral("severity")).toString() == QLatin1String("error") ? 1 : 0;
    return n;
}

QVariantList SchemaDesign::problemsFor(const QString &table) const
{
    QVariantList out;
    for (const QVariant &p : m_problems)
        if (p.toMap().value(QStringLiteral("table")).toString() == table)
            out << p;
    return out;
}

qint64 SchemaDesign::scalar(const QString &sql) const
{
    if (!m_session || !m_session->isOpen())
        return -1;
    QSqlQuery q(QSqlDatabase::database(m_session->connectionName()));
    if (!q.exec(sql) || !q.next())
        return -1;
    return q.value(0).toLongLong();
}

void SchemaDesign::validate()
{
    QVariantList errors, warnings;
    // `fix`: a one-click way out the UI can offer ("allowEmpty").
    auto add = [&](const QString &severity, const QString &table, const QString &column, const QString &message,
                   const QString &fix = QString()) {
        (severity == QLatin1String("error") ? errors : warnings)
            << QVariantMap{ { QStringLiteral("severity"), severity }, { QStringLiteral("table"), table },
                            { QStringLiteral("column"), column }, { QStringLiteral("message"), message },
                            { QStringLiteral("fix"), fix } };
    };
    auto plural = [](qint64 n, const char *one, const char *many) {
        return QStringLiteral("%1 %2").arg(QLocale().toString(n), QString::fromLatin1(n == 1 ? one : many));
    };
    const bool live = m_session && m_session->isOpen();

    // The C++ generator's notes (names Qivot can't use, no key, ...).
    const CodeGen gen(infos(), m_dialect);
    for (const CodeGen::Model &m : gen.models())
        for (const CodeGen::Warning &w : m.warnings)
            add(QStringLiteral("warning"), m.table, w.column, w.message);

    for (const DesignTable &t : m_tables) {
        const QString name = t.info.name;
        const QiTableInfo *before = nullptr;
        for (const QiTableInfo &o : m_original)
            if (o.name == t.origin)
                before = &o;
        const QString sqlTable = before && live ? m_session->sqlName(before->name) : QString();
        const qint64 rows = before ? scalar(QStringLiteral("SELECT COUNT(*) FROM ") + sqlTable) : 0;

        if (t.info.columns.isEmpty())
            add(QStringLiteral("error"), name, QString(), tr("A table needs at least one column."));

        // References: to a key, and with a type that can hold it.
        for (const QiForeignKeyInfo &fk : t.info.foreignKeys) {
            const DesignTable *target = find(fk.refTable);
            if (!target) {
                add(QStringLiteral("error"), name, fk.columns.join(QStringLiteral(", ")),
                    tr("References %1, which isn't in the design.").arg(fk.refTable));
                continue;
            }
            if (fk.refColumns != target->info.primaryKey)
                add(QStringLiteral("warning"), name, fk.columns.join(QStringLiteral(", ")),
                    tr("References %1 (%2), which isn't its primary key.").arg(fk.refTable, fk.refColumns.join(QStringLiteral(", "))));
            for (int i = 0; i < fk.columns.size() && i < fk.refColumns.size(); ++i) {
                const QiColumnInfo *c = t.info.column(fk.columns.at(i));
                const QiColumnInfo *k = target->info.column(fk.refColumns.at(i));
                if (c && k && CodeGen::cppType(c->type) != CodeGen::cppType(k->type))
                    add(QStringLiteral("error"), name, c->name,
                        tr("Is %1 but references %2.%3, which is %4.").arg(c->type, fk.refTable, k->name, k->type));
            }
        }

        if (!before || rows <= 0)
            continue;               // a new or empty table: nothing in the data to clash with

        // Against the data in the database.
        for (int i = 0; i < t.info.columns.size(); ++i) {
            const QiColumnInfo &c = t.info.columns.at(i);
            const QString origin = t.columnOrigins.value(i);
            const QiColumnInfo *was = origin.isEmpty() ? nullptr : before->column(origin);
            const bool required = !c.nullable && !t.info.primaryKey.contains(c.name);
            if (!was) {
                if (required && defaultOf(c).isEmpty() && !c.autoIncrement) {
                    QString reference;
                    for (const QiForeignKeyInfo &fk : t.info.foreignKeys)
                        if (fk.columns == QStringList{ c.name })
                            reference = fk.refTable;
                    add(QStringLiteral("error"), name, c.name,
                        reference.isEmpty()
                            ? tr("Required, with no default, but %1 already has %2: they'd have no value. "
                                 "Give it a default, or let it be empty.").arg(name, plural(rows, "row", "rows"))
                            : tr("Required, with no default, but %1 already has %2: they'd have no value. "
                                 "Let it be empty for now (fill it in, then make it required), or give it a "
                                 "default that is an existing %3 row.").arg(name, plural(rows, "row", "rows"), reference),
                        QStringLiteral("allowEmpty"));
                } else if (!defaultOf(c).isEmpty()) {
                    // Every existing row gets the default: for a reference it has
                    // to be a row of the referenced table.
                    for (const QiForeignKeyInfo &fk : t.info.foreignKeys) {
                        if (fk.columns != QStringList{ c.name } || fk.refColumns.size() != 1)
                            continue;
                        const DesignTable *target = find(fk.refTable);
                        if (!target)
                            continue;
                        const int keyIndex = columnIndex(target->info, fk.refColumns.first());
                        const QString keyOrigin = keyIndex >= 0 ? target->columnOrigins.value(keyIndex) : QString();
                        const bool exists = !target->origin.isEmpty() && !keyOrigin.isEmpty()
                            && scalar(QStringLiteral("SELECT COUNT(*) FROM %1 WHERE %2 = %3")
                                          .arg(m_session->sqlName(target->origin), Migration::quoted(keyOrigin, m_dialect),
                                               defaultOf(c))) != 0;   // -1: couldn't tell (a function, say)
                        if (!exists)
                            add(QStringLiteral("error"), name, c.name,
                                tr("Defaults to %1, but %2 has no row %1%3: all %4 would point at nothing. "
                                   "Let it be empty for now (fill it in, then make it required).")
                                    .arg(defaultOf(c), fk.refTable,
                                         target->origin.isEmpty() ? tr(" (it's a new, empty table)") : QString(),
                                         plural(rows, "row", "rows")),
                                QStringLiteral("allowEmpty"));
                    }
                }
                continue;
            }
            const QString col = Migration::quoted(origin, m_dialect);
            if (required && was->nullable) {
                const qint64 nulls = scalar(QStringLiteral("SELECT COUNT(*) FROM %1 WHERE %2 IS NULL").arg(sqlTable, col));
                if (nulls > 0)
                    add(QStringLiteral("error"), name, c.name,
                        tr("Required, but %1 have no value.").arg(plural(nulls, "row", "rows")), QStringLiteral("allowEmpty"));
            }
            if (isUnique(t.info, c.name) && !isUnique(*before, origin) && t.info.primaryKey != QStringList{ c.name }) {
                const qint64 dupes = scalar(QStringLiteral("SELECT COUNT(%2) - COUNT(DISTINCT %2) FROM %1").arg(sqlTable, col));
                if (dupes > 0)
                    add(QStringLiteral("error"), name, c.name,
                        tr("Unique, but %1 repeat an earlier value.").arg(plural(dupes, "row", "rows")));
            }
            if (c.type.trimmed().compare(was->type.trimmed(), Qt::CaseInsensitive) != 0
                && CodeGen::cppType(c.type) != CodeGen::cppType(was->type))
                add(QStringLiteral("warning"), name, c.name,
                    tr("Changes from %1 to %2: values that don't convert may be lost or refused.").arg(was->type, c.type));
        }

        // New references on existing columns to existing tables: values that point nowhere.
        for (const QiForeignKeyInfo &fk : t.info.foreignKeys) {
            if (fk.columns.size() != 1)
                continue;
            const int index = columnIndex(t.info, fk.columns.first());
            const QString origin = index >= 0 ? t.columnOrigins.value(index) : QString();
            const DesignTable *target = find(fk.refTable);
            if (origin.isEmpty() || !target || target->origin.isEmpty() || fk.refColumns.size() != 1)
                continue;
            bool existed = false;
            for (const QiForeignKeyInfo &old : before->foreignKeys)
                existed = existed || (old.columns == QStringList{ origin } && old.refTable == target->origin);
            const int keyIndex = columnIndex(target->info, fk.refColumns.first());
            const QString keyOrigin = keyIndex >= 0 ? target->columnOrigins.value(keyIndex) : QString();
            if (existed || keyOrigin.isEmpty())
                continue;
            const QString col = Migration::quoted(origin, m_dialect);
            const qint64 orphans = scalar(QStringLiteral("SELECT COUNT(*) FROM %1 WHERE %2 IS NOT NULL AND %2 NOT IN (SELECT %3 FROM %4)")
                                              .arg(sqlTable, col, Migration::quoted(keyOrigin, m_dialect),
                                                   m_session->sqlName(target->origin)));
            if (orphans > 0)
                add(QStringLiteral("error"), name, fk.columns.first(),
                    tr("%1 point at no %2 row.").arg(plural(orphans, "row", "rows"), fk.refTable));
        }

        // What goes away with dropped columns.
        for (const QiColumnInfo &c : before->columns)
            if (!t.columnOrigins.contains(c.name))
                add(QStringLiteral("warning"), name, c.name,
                    tr("Dropped, with its values in %1.").arg(plural(rows, "row", "rows")));
    }
    for (const QiTableInfo &o : m_original) {
        bool kept = false;
        for (const DesignTable &t : m_tables)
            kept = kept || t.origin == o.name;
        if (!kept) {
            const qint64 rows = live ? scalar(QStringLiteral("SELECT COUNT(*) FROM ") + m_session->sqlName(o.name)) : 0;
            if (rows > 0)
                add(QStringLiteral("warning"), o.name, QString(),
                    tr("Dropped, with its %1.").arg(plural(rows, "row", "rows")));
        }
    }

    m_problems = errors + warnings;
    emit problemsChanged();
}

void SchemaDesign::setSession(DatabaseSession *session)
{
    if (session == m_session)
        return;
    if (m_session)
        disconnect(m_session, nullptr, this, nullptr);
    m_session = session;
    if (m_session)
        connect(m_session, &DatabaseSession::openChanged, this, [this] { openSession(); });
    emit sessionChanged();
    openSession();
}

void SchemaDesign::reset()
{
    if (m_session && m_session->isOpen())
        reset(m_session->tableInfos(), m_session->dialect());
    else
        reset({}, QStringLiteral("sqlite"));
}

void SchemaDesign::discard()
{
    const QString path = autosavePath();
    if (!path.isEmpty())
        QFile::remove(path);
    m_filePath.clear();
    reset();
}

void SchemaDesign::openSession()
{
    m_loading = true;                       // don't autosave the database's own state over the saved design
    reset();
    m_loading = false;
    if (restoreAutosave()) {
        m_loading = true;
        emit designChanged();
        m_loading = false;
    }
}

void SchemaDesign::reset(const QVector<QiTableInfo> &original, const QString &dialect)
{
    m_dialect = dialect;
    m_original.clear();
    m_tables.clear();
    for (QiTableInfo t : original) {
        if (t.kind != QiTableInfo::Table)
            continue;
        // Defaults as SQL text, the same on both sides of the comparison.
        for (QiColumnInfo &c : t.columns) {
            const QString d = CodeGen::defaultExpression(c.defaultValue, dialect);
            c.defaultValue = d.isEmpty() || c.autoIncrement ? QVariant() : QVariant(d);
        }
        m_original << t;
        DesignTable d;
        d.info = t;
        d.origin = t.name;
        for (const QiColumnInfo &c : t.columns)
            d.columnOrigins << c.name;
        m_tables << d;
    }
    m_undo.clear();
    m_redo.clear();
    m_restored = false;
    m_filePath.clear();
    setError(QString());
    emit designChanged();
}

QVariantList SchemaDesign::tables() const
{
    QVariantList out;
    for (const DesignTable &t : m_tables)
        out << QVariantMap{ { QStringLiteral("name"), t.info.name },
                            { QStringLiteral("isNew"), t.origin.isEmpty() },
                            { QStringLiteral("columns"), t.info.columns.size() } };
    return out;
}

QStringList SchemaDesign::typeSuggestions() const
{
    if (m_dialect == QLatin1String("postgres"))
        return { QStringLiteral("integer"), QStringLiteral("bigint"), QStringLiteral("text"), QStringLiteral("varchar(255)"),
                 QStringLiteral("numeric(10,2)"), QStringLiteral("double precision"), QStringLiteral("boolean"),
                 QStringLiteral("date"), QStringLiteral("timestamp"), QStringLiteral("time"), QStringLiteral("bytea"),
                 QStringLiteral("uuid"), QStringLiteral("jsonb") };
    if (m_dialect == QLatin1String("mysql"))
        return { QStringLiteral("INT"), QStringLiteral("BIGINT"), QStringLiteral("VARCHAR(255)"), QStringLiteral("TEXT"),
                 QStringLiteral("DECIMAL(10,2)"), QStringLiteral("DOUBLE"), QStringLiteral("TINYINT(1)"),
                 QStringLiteral("DATE"), QStringLiteral("DATETIME"), QStringLiteral("TIME"), QStringLiteral("BLOB"),
                 QStringLiteral("JSON") };
    if (m_dialect == QLatin1String("sqlserver"))
        return { QStringLiteral("INT"), QStringLiteral("BIGINT"), QStringLiteral("NVARCHAR(255)"), QStringLiteral("NVARCHAR(MAX)"),
                 QStringLiteral("DECIMAL(10,2)"), QStringLiteral("FLOAT"), QStringLiteral("BIT"), QStringLiteral("DATE"),
                 QStringLiteral("DATETIME2"), QStringLiteral("TIME"), QStringLiteral("VARBINARY(MAX)") };
    return { QStringLiteral("INTEGER"), QStringLiteral("TEXT"), QStringLiteral("REAL"), QStringLiteral("NUMERIC"),
             QStringLiteral("BOOLEAN"), QStringLiteral("DATE"), QStringLiteral("DATETIME"), QStringLiteral("BLOB") };
}

