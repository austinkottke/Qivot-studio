{
    for (const DesignTable &t : m_tables)
        if (t.info.name == name)
            return &t;
    return nullptr;
}

QString SchemaDesign::uniqueTableName(const QString &base) const
{
    QString name = base;
    for (int n = 2; find(name); ++n)
        name = base + QString::number(n);
    return name;
}

void SchemaDesign::edit()
{
    m_restored = false;
    m_undo << m_tables;
    if (m_undo.size() > 200)
        m_undo.removeFirst();
    m_redo.clear();
}

void SchemaDesign::setError(const QString &error)
{
    if (error == m_error)
        return;
    m_error = error;
    emit errorChanged();
}

QVariantMap SchemaDesign::table(const QString &name) const
{
    const DesignTable *t = find(name);
    if (!t)
        return {};
    QVariantList columns;
    for (int i = 0; i < t->info.columns.size(); ++i) {
        const QiColumnInfo &c = t->info.columns.at(i);
        QString reference, onDelete;
        for (const QiForeignKeyInfo &fk : t->info.foreignKeys)
            if (fk.columns == QStringList{ c.name }) {
                reference = fk.refTable;
                onDelete = fk.onDelete;
            }
        columns << QVariantMap{
            { QStringLiteral("name"), c.name },
            { QStringLiteral("type"), c.type },
            { QStringLiteral("nullable"), c.nullable },
            { QStringLiteral("primaryKey"), t->info.primaryKey.contains(c.name) },
            { QStringLiteral("autoIncrement"), c.autoIncrement },
            { QStringLiteral("unique"), isUnique(t->info, c.name) },
            { QStringLiteral("defaultValue"), defaultOf(c) },
            { QStringLiteral("reference"), reference },
            { QStringLiteral("onDelete"), onDelete },
            { QStringLiteral("isNew"), t->columnOrigins.value(i).isEmpty() },
        };
    }
    QStringList referencedBy;
    for (const DesignTable &other : m_tables)
        for (const QiForeignKeyInfo &fk : other.info.foreignKeys)
            if (fk.refTable == name && !referencedBy.contains(other.info.name))
                referencedBy << other.info.name;
    return { { QStringLiteral("name"), t->info.name },
             { QStringLiteral("isNew"), t->origin.isEmpty() },
             { QStringLiteral("origin"), t->origin },
             { QStringLiteral("columns"), columns },
             { QStringLiteral("referencedBy"), referencedBy } };
}

QString SchemaDesign::addTable(const QString &requested)
{
    edit();
    DesignTable t;
    t.info.name = uniqueTableName(requested.trimmed().isEmpty() ? QStringLiteral("new_table") : requested.trimmed());
    QiColumnInfo id;
    id.name = QStringLiteral("id");
    id.type = typeSuggestions().first();
    id.nullable = false;
    id.primaryKey = true;
    id.primaryKeyOrder = 1;
    id.autoIncrement = true;
    t.info.columns << id;
    t.info.primaryKey << id.name;
    t.columnOrigins << QString();
    m_tables << t;
    emit designChanged();
    return t.info.name;
}

bool SchemaDesign::renameTable(const QString &name, const QString &newName)
{
    const QString to = newName.trimmed();
    DesignTable *t = find(name);
    if (!t || to.isEmpty() || to == name)
        return false;
    if (find(to)) {
        setError(tr("There's already a table called %1.").arg(to));
        return false;
    }
    edit();
    t = find(name);
    t->info.name = to;
    for (DesignTable &other : m_tables)
        for (QiForeignKeyInfo &fk : other.info.foreignKeys)
            if (fk.refTable == name)
                fk.refTable = to;
    setError(QString());
    emit designChanged();
    return true;
}

void SchemaDesign::removeTable(const QString &name)
{
    if (!find(name))
        return;
    edit();
    for (int i = 0; i < m_tables.size(); ++i)
        if (m_tables[i].info.name == name)
            m_tables.removeAt(i--);
    for (DesignTable &other : m_tables)
        for (int i = 0; i < other.info.foreignKeys.size(); ++i)
            if (other.info.foreignKeys[i].refTable == name)
                other.info.foreignKeys.removeAt(i--);
    emit designChanged();
}

QString SchemaDesign::addColumn(const QString &table, const QString &requested, const QString &type)
{
    if (!find(table))
        return QString();
    edit();
    DesignTable *t = find(table);
    const QString base = requested.trimmed().isEmpty() ? QStringLiteral("new_column") : requested.trimmed();
    QString name = base;
    for (int n = 2; t->info.column(name); ++n)
        name = base + QString::number(n);
    QiColumnInfo c;
    c.name = name;
    c.type = type.isEmpty() ? typeSuggestions().value(1) : type;
    t->info.columns << c;
    t->columnOrigins << QString();
    emit designChanged();
    return name;
}

bool SchemaDesign::updateColumn(const QString &table, int index, const QVariantMap &changes)
{
    const DesignTable *current = find(table);
    if (!current || index < 0 || index >= current->info.columns.size())
        return false;
    const QString oldName = current->info.columns.at(index).name;
    if (changes.contains(QStringLiteral("name"))) {
        const QString newName = changes.value(QStringLiteral("name")).toString().trimmed();
        if (newName.isEmpty())
            return false;
        if (newName != oldName && current->info.column(newName)) {
            setError(tr("%1 already has a column called %2.").arg(table, newName));
            return false;
        }
    }
    edit();
    DesignTable *t = find(table);
    QiColumnInfo &c = t->info.columns[index];

    if (changes.contains(QStringLiteral("name"))) {
        const QString newName = changes.value(QStringLiteral("name")).toString().trimmed();
        c.name = newName;
        for (QString &k : t->info.primaryKey)
            if (k == oldName) k = newName;
        for (QiForeignKeyInfo &fk : t->info.foreignKeys)
            for (QString &k : fk.columns)
                if (k == oldName) k = newName;
        for (QiIndexInfo &i : t->info.indexes)
            for (QString &k : i.columns)
                if (k == oldName) k = newName;
        for (DesignTable &other : m_tables)            // references to this column
            for (QiForeignKeyInfo &fk : other.info.foreignKeys)
                if (fk.refTable == table)
                    for (QString &k : fk.refColumns)
                        if (k == oldName) k = newName;
    }
    if (changes.contains(QStringLiteral("type")))
        c.type = changes.value(QStringLiteral("type")).toString().trimmed();
    if (changes.contains(QStringLiteral("nullable")))
        c.nullable = changes.value(QStringLiteral("nullable")).toBool();
    if (changes.contains(QStringLiteral("defaultValue"))) {
        const QString d = changes.value(QStringLiteral("defaultValue")).toString().trimmed();
        c.defaultValue = d.isEmpty() ? QVariant() : QVariant(d);
    }
    if (changes.contains(QStringLiteral("primaryKey"))) {
        const bool key = changes.value(QStringLiteral("primaryKey")).toBool();
        t->info.primaryKey.removeAll(c.name);
        if (key) {
            // Keep the key in column order.
            QStringList ordered;
            for (const QiColumnInfo &col : t->info.columns)
                if (col.name == c.name || t->info.primaryKey.contains(col.name))
                    ordered << col.name;
            t->info.primaryKey = ordered;
            c.nullable = false;
        } else {
            c.autoIncrement = false;
        }
        for (int i = 0; i < t->info.columns.size(); ++i) {
            t->info.columns[i].primaryKey = t->info.primaryKey.contains(t->info.columns[i].name);
            t->info.columns[i].primaryKeyOrder = t->info.primaryKey.indexOf(t->info.columns[i].name) + 1;
            if (t->info.primaryKey.size() > 1)
                t->info.columns[i].autoIncrement = false;
        }
    }
    if (changes.contains(QStringLiteral("unique"))) {
        const bool unique = changes.value(QStringLiteral("unique")).toBool();
        for (int i = 0; i < t->info.indexes.size(); ++i)
            if (t->info.indexes[i].unique && t->info.indexes[i].columns == QStringList{ c.name })
                t->info.indexes.removeAt(i--);
        if (unique) {
            QiIndexInfo index;
            index.columns << c.name;
            index.unique = true;
            index.implicit = true;
            t->info.indexes << index;
        }
    }
    setError(QString());
    emit designChanged();
    return true;
}

void SchemaDesign::removeColumn(const QString &table, int index)
{
    const DesignTable *current = find(table);
    if (!current || index < 0 || index >= current->info.columns.size())
        return;
    edit();
    DesignTable *t = find(table);
    const QString name = t->info.columns.at(index).name;
    t->info.columns.removeAt(index);
    t->columnOrigins.removeAt(index);
    t->info.primaryKey.removeAll(name);
    for (int i = 0; i < t->info.foreignKeys.size(); ++i)
        if (t->info.foreignKeys[i].columns.contains(name))
            t->info.foreignKeys.removeAt(i--);
    for (int i = 0; i < t->info.indexes.size(); ++i)
        if (t->info.indexes[i].columns.contains(name))
            t->info.indexes.removeAt(i--);
    for (DesignTable &other : m_tables)
        for (int i = 0; i < other.info.foreignKeys.size(); ++i)
            if (other.info.foreignKeys[i].refTable == table && other.info.foreignKeys[i].refColumns.contains(name))
                other.info.foreignKeys.removeAt(i--);
    emit designChanged();
}

void SchemaDesign::moveColumn(const QString &table, int from, int to)
{
    const DesignTable *current = find(table);
    if (!current || from == to || from < 0 || to < 0 || from >= current->info.columns.size()
        || to >= current->info.columns.size())
        return;
    edit();
    DesignTable *t = find(table);
    t->info.columns.move(from, to);
    t->columnOrigins.move(from, to);
    emit designChanged();
}

bool SchemaDesign::setReference(const QString &table, const QString &column, const QString &refTable,
                                const QString &onDelete)
{
    const DesignTable *current = find(table);
    if (!current || !current->info.column(column))
        return false;
    const DesignTable *target = refTable.isEmpty() ? nullptr : find(refTable);
    if (!refTable.isEmpty() && (!target || target->info.primaryKey.size() != 1)) {
        setError(tr("%1 needs a single-column primary key to be referenced.").arg(refTable));
        return false;
    }
    edit();
    DesignTable *t = find(table);
    for (int i = 0; i < t->info.foreignKeys.size(); ++i)
        if (t->info.foreignKeys[i].columns == QStringList{ column })
            t->info.foreignKeys.removeAt(i--);
    if (target) {
        QiForeignKeyInfo fk;
        fk.columns << column;
        fk.refTable = refTable;
        fk.refColumns = target->info.primaryKey;
        fk.onDelete = onDelete;
        t->info.foreignKeys << fk;
        // The column takes the key's type, so the reference can hold it.
        const QiColumnInfo *key = target->info.column(target->info.primaryKey.first());
        QiColumnInfo *c = nullptr;
        for (QiColumnInfo &col : t->info.columns)
            if (col.name == column)
                c = &col;
        if (key && c && CodeGen::cppType(c->type) != CodeGen::cppType(key->type))
            c->type = key->type.contains(QLatin1String("serial"), Qt::CaseInsensitive) ? QStringLiteral("integer") : key->type;
    }
    setError(QString());
    emit designChanged();
    return true;
}

QString SchemaDesign::addReference(const QString &table, const QString &refTable, const QString &onDelete)
{
    const DesignTable *t = find(table);
    const DesignTable *target = find(refTable);
    if (!t || !target || target->info.primaryKey.size() != 1) {
        setError(tr("%1 needs a single-column primary key to be referenced.").arg(refTable));
        return QString();
    }
    const QString key = target->info.primaryKey.first();
    const QString bare = bareName(refTable);
    // book -> category: "category_id"; to a key already named category_id: "category_id".
    const QString base = key.startsWith(bare, Qt::CaseInsensitive) ? key : bare + QLatin1Char('_') + key;
    QString name = base;
    for (int n = 2; t->info.column(name); ++n)
        name = base + QString::number(n);

    // One undo step for the column and its reference together.
    const QiColumnInfo *k = target->info.column(key);
    edit();
    DesignTable *mine = find(table);
    QiColumnInfo c;
    c.name = name;
    c.type = k && k->type.contains(QLatin1String("serial"), Qt::CaseInsensitive) ? QStringLiteral("integer")
           : k ? k->type : typeSuggestions().first();
    mine->info.columns << c;
    mine->columnOrigins << QString();
    QiForeignKeyInfo fk;
    fk.columns << name;
    fk.refTable = refTable;
    fk.refColumns << key;
    fk.onDelete = onDelete;
    mine->info.foreignKeys << fk;
    setError(QString());
    emit designChanged();
    return name;
}

bool SchemaDesign::setOnDelete(const QString &table, const QString &column, const QString &onDelete)
{
    const DesignTable *t = find(table);
    if (!t)
        return false;
    int index = -1;
    for (int i = 0; i < t->info.foreignKeys.size(); ++i)
        if (t->info.foreignKeys.at(i).columns == QStringList{ column })
            index = i;
    if (index < 0 || t->info.foreignKeys.at(index).onDelete == onDelete)
        return false;
    edit();
    find(table)->info.foreignKeys[index].onDelete = onDelete;
    emit designChanged();
    return true;
}

void SchemaDesign::undo()
{
    if (m_undo.isEmpty())
        return;
    m_redo << m_tables;
    m_tables = m_undo.takeLast();
    emit designChanged();
}

void SchemaDesign::redo()
{
    if (m_redo.isEmpty())
        return;
    m_undo << m_tables;
    m_tables = m_redo.takeLast();
    emit designChanged();
}

