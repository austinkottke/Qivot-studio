QJsonObject tableToJson(const QiTableInfo &t)
{
    QJsonArray columns, foreignKeys, indexes;
    for (const QiColumnInfo &c : t.columns)
        columns << QJsonObject{ { QStringLiteral("name"), c.name }, { QStringLiteral("type"), c.type },
                                { QStringLiteral("nullable"), c.nullable }, { QStringLiteral("primaryKeyOrder"), c.primaryKeyOrder },
                                { QStringLiteral("autoIncrement"), c.autoIncrement },
                                { QStringLiteral("default"), c.defaultValue.isNull() ? QJsonValue() : QJsonValue(c.defaultValue.toString()) } };
    for (const QiForeignKeyInfo &fk : t.foreignKeys)
        foreignKeys << QJsonObject{ { QStringLiteral("name"), fk.name },
                                    { QStringLiteral("columns"), QJsonArray::fromStringList(fk.columns) },
                                    { QStringLiteral("refTable"), fk.refTable },
                                    { QStringLiteral("refColumns"), QJsonArray::fromStringList(fk.refColumns) },
                                    { QStringLiteral("onDelete"), fk.onDelete }, { QStringLiteral("onUpdate"), fk.onUpdate } };
    for (const QiIndexInfo &i : t.indexes)
        indexes << QJsonObject{ { QStringLiteral("name"), i.name }, { QStringLiteral("columns"), QJsonArray::fromStringList(i.columns) },
                                { QStringLiteral("unique"), i.unique }, { QStringLiteral("implicit"), i.implicit } };
    return { { QStringLiteral("name"), t.name }, { QStringLiteral("schema"), t.schema },
             { QStringLiteral("primaryKey"), QJsonArray::fromStringList(t.primaryKey) },
             { QStringLiteral("columns"), columns }, { QStringLiteral("foreignKeys"), foreignKeys },
             { QStringLiteral("indexes"), indexes } };
}

QStringList strings(const QJsonValue &v)
{
    QStringList out;
    for (const QJsonValue &s : v.toArray())
        out << s.toString();
    return out;
}

QiTableInfo tableFromJson(const QJsonObject &o)
{
    QiTableInfo t;
    t.name = o.value(QStringLiteral("name")).toString();
    t.schema = o.value(QStringLiteral("schema")).toString();
    t.kind = QiTableInfo::Table;
    t.primaryKey = strings(o.value(QStringLiteral("primaryKey")));
    for (const QJsonValue &v : o.value(QStringLiteral("columns")).toArray()) {
        const QJsonObject c = v.toObject();
        QiColumnInfo col;
        col.name = c.value(QStringLiteral("name")).toString();
        col.type = c.value(QStringLiteral("type")).toString();
        col.nullable = c.value(QStringLiteral("nullable")).toBool(true);
        col.primaryKeyOrder = c.value(QStringLiteral("primaryKeyOrder")).toInt();
        col.primaryKey = t.primaryKey.contains(col.name);
        col.autoIncrement = c.value(QStringLiteral("autoIncrement")).toBool();
        const QJsonValue d = c.value(QStringLiteral("default"));
        col.defaultValue = d.isString() ? QVariant(d.toString()) : QVariant();
        t.columns << col;
    }
    for (const QJsonValue &v : o.value(QStringLiteral("foreignKeys")).toArray()) {
        const QJsonObject f = v.toObject();
        QiForeignKeyInfo fk;
        fk.name = f.value(QStringLiteral("name")).toString();
        fk.columns = strings(f.value(QStringLiteral("columns")));
        fk.refTable = f.value(QStringLiteral("refTable")).toString();
        fk.refColumns = strings(f.value(QStringLiteral("refColumns")));
        fk.onDelete = f.value(QStringLiteral("onDelete")).toString();
        fk.onUpdate = f.value(QStringLiteral("onUpdate")).toString();
        t.foreignKeys << fk;
    }
    for (const QJsonValue &v : o.value(QStringLiteral("indexes")).toArray()) {
        const QJsonObject i = v.toObject();
        QiIndexInfo index;
        index.name = i.value(QStringLiteral("name")).toString();
        index.columns = strings(i.value(QStringLiteral("columns")));
        index.unique = i.value(QStringLiteral("unique")).toBool();
        index.implicit = i.value(QStringLiteral("implicit")).toBool();
        t.indexes << index;
    }
    return t;
}

QJsonArray schemaToJson(const QVector<QiTableInfo> &tables)
{
    QJsonArray out;
    for (const QiTableInfo &t : tables)
        out << tableToJson(t);
    return out;
}

QString localPath(const QVariant &fileOrUrl)
{
    const QString text = fileOrUrl.toString();
    return text.startsWith(QLatin1String("file:")) ? QUrl(text).toLocalFile() : text;
}

