QString Migration::quoted(const QString &identifier, const QString &dialect)
{
    return qt(identifier, dialect);
}

// CREATE INDEX for the indexes CREATE TABLE doesn't write: all but the key
// and single-column unique ones (which are inline).
static QString createIndexes(const QiTableInfo &t, const QString &dialect)
{
    QString sql;
    for (const QiIndexInfo &i : t.indexes) {
        if (i.columns.isEmpty() || i.columns.contains(QString()) || i.columns == t.primaryKey
            || (i.unique && i.columns.size() == 1))
            continue;
        const QString name = i.implicit || i.name.isEmpty() ? constraintName(i.unique ? QStringLiteral("ux") : QStringLiteral("ix"), t.name, i.columns)
                                                            : bareName(i.name);
        sql += QStringLiteral("CREATE %1INDEX %2 ON %3 (%4);\n")
                   .arg(i.unique ? QStringLiteral("UNIQUE ") : QString(), quoteOne(name, dialect), qt(t.name, dialect),
                        qlist(i.columns, dialect));
    }
    return sql;
}

QString Migration::createTable(const QiTableInfo &t, const QString &dialect)
{
    QStringList parts;
    for (const QiColumnInfo &c : t.columns)
        parts << QStringLiteral("    ") + columnDefinition(t, c, dialect, true);
    if (t.primaryKey.size() > 1)
        parts << QStringLiteral("    PRIMARY KEY (%1)").arg(qlist(t.primaryKey, dialect));
    for (const QiForeignKeyInfo &fk : t.foreignKeys)
        parts << QStringLiteral("    ") + fkClause(fk, dialect);
    return QStringLiteral("CREATE TABLE %1 (\n%2\n);\n").arg(qt(t.name, dialect), parts.join(QStringLiteral(",\n")))
         + createIndexes(t, dialect);
}

QString Migration::sql(const QVector<QiTableInfo> &original, const QVector<DesignTable> &design, const QString &dialect)
{
    const Diff d = diff(original, design);
    if (d.droppedTables.isEmpty() && d.createdTables.isEmpty() && d.tables.isEmpty())
        return QString();

    const bool sqlite = dialect == QLatin1String("sqlite");
    const bool mysql = dialect == QLatin1String("mysql");
    const bool mssql = dialect == QLatin1String("sqlserver");
    const bool pg = dialect == QLatin1String("postgres");
    QStringList out;
    auto section = [&](const QString &title) { out << QStringLiteral("\n-- %1").arg(title); };

    bool rebuilds = false;
    for (const TableDiff &t : d.tables)
        rebuilds = rebuilds || (sqlite && t.sqliteNeedsRebuild());
    if (rebuilds)
        out << QStringLiteral("PRAGMA foreign_keys = OFF;   -- while tables are rebuilt");
    if (sqlite || pg)
        out << QStringLiteral("BEGIN;");
    else if (mssql)
        out << QStringLiteral("BEGIN TRANSACTION;");
    else
        out << QStringLiteral("-- MySQL commits each schema change as it goes; there is no undoing half of this.");

    // 1. Foreign keys that go away (not SQLite: there they go with the rebuild).
    if (!sqlite) {
        bool first = true;
        for (const TableDiff &t : d.tables)
            for (const QiForeignKeyInfo &fk : t.droppedKeys) {
                if (first) { section(QStringLiteral("Foreign keys that change or go away")); first = false; }
                if (fk.name.isEmpty())
                    out << QStringLiteral("-- %1 (%2): this foreign key has no name; drop it by hand.")
                               .arg(t.before->name, fk.columns.join(QStringLiteral(", ")));
                else
                    out << QStringLiteral("ALTER TABLE %1 DROP %2 %3;")
                               .arg(qt(t.before->name, dialect), mysql ? QStringLiteral("FOREIGN KEY") : QStringLiteral("CONSTRAINT"),
                                    quoteOne(fk.name, dialect));
            }
    }

    // 2. Tables that go away.
    if (!d.droppedTables.isEmpty()) {
        section(QStringLiteral("Tables that go away (and their rows)"));
        for (const QiTableInfo *t : d.droppedTables)
            out << QStringLiteral("DROP TABLE %1;").arg(qt(t->name, dialect));
    }

    // 3. Renames, so everything below can use the new names. (SQLite too before
    //    a rebuild: its RENAME also updates the other tables' references.)
    QStringList renames;
    for (const TableDiff &t : d.tables) {
        const QString table = qt(t.after->info.name, dialect);
        if (t.renamed) {
            if (mssql)
                renames << QStringLiteral("EXEC sp_rename '%1', '%2';").arg(t.before->name, bareName(t.after->info.name));
            else if (mysql)
                renames << QStringLiteral("RENAME TABLE %1 TO %2;").arg(qt(t.before->name, dialect), table);
            else
                renames << QStringLiteral("ALTER TABLE %1 RENAME TO %2;").arg(qt(t.before->name, dialect), quoteOne(bareName(t.after->info.name), dialect));
        }
        for (const ColumnChange &c : t.changedColumns)
            if (c.renamed) {
                if (mssql)
                    renames << QStringLiteral("EXEC sp_rename '%1.%2', '%3', 'COLUMN';").arg(t.after->info.name, c.before->name, c.after->name);
                else
                    renames << QStringLiteral("ALTER TABLE %1 RENAME COLUMN %2 TO %3;")
                                   .arg(table, quoteOne(c.before->name, dialect), quoteOne(c.after->name, dialect));
            }
    }
    if (!renames.isEmpty()) {
        section(QStringLiteral("Renames"));
        out << renames;
    }

    // 4. New tables.
    const QVector<const DesignTable *> created = creationOrder(d.createdTables);
    if (!created.isEmpty()) {
        section(QStringLiteral("New tables"));
        for (const DesignTable *t : created)
            out << createTable(t->info, dialect).trimmed();
    }

    // 5. Changes to existing tables.
    for (const TableDiff &t : d.tables) {
        const QString table = qt(t.after->info.name, dialect);
        QStringList lines;
        if (sqlite && t.sqliteNeedsRebuild()) {
            // Rebuild: the new shape under a temporary name, the rows copied across by origin.
            const QString temp = QStringLiteral("_new_") + bareName(t.after->info.name);
            QiTableInfo shaped = t.after->info;
            shaped.name = temp;
            QStringList kept;                   // already renamed above, so the same name on both sides
            for (int i = 0; i < t.after->info.columns.size(); ++i) {
                const QString origin = t.after->columnOrigins.value(i);
                if (!origin.isEmpty() && t.before->column(origin))
                    kept << quoteOne(t.after->info.columns.at(i).name, dialect);
            }
            lines << QStringLiteral("-- SQLite can't alter these columns in place: rebuild %1, keeping its rows.")
                         .arg(t.after->info.name);
            QiTableInfo bare = shaped;
            bare.indexes.erase(std::remove_if(bare.indexes.begin(), bare.indexes.end(), [&](const QiIndexInfo &i) {
                                   return !(i.unique && i.columns.size() == 1); }),
                               bare.indexes.end());
            lines << createTable(bare, dialect).trimmed();
            if (!kept.isEmpty())
                lines << QStringLiteral("INSERT INTO %1 (%2)\n    SELECT %2 FROM %3;")
                             .arg(quoteOne(temp, dialect), kept.join(QStringLiteral(", ")), table);
            lines << QStringLiteral("DROP TABLE %1;").arg(table);
            lines << QStringLiteral("ALTER TABLE %1 RENAME TO %2;").arg(quoteOne(temp, dialect), quoteOne(bareName(t.after->info.name), dialect));
            // The other indexes went with the old table; recreate them on the new one.
            const QString indexes = createIndexes(t.after->info, dialect).trimmed();
            if (!indexes.isEmpty())
                lines << indexes;
        } else {
            for (const QString &c : t.droppedColumns)
                lines << QStringLiteral("ALTER TABLE %1 DROP COLUMN %2;").arg(table, quoteOne(c, dialect));
            for (const QiColumnInfo *c : t.addedColumns) {
                lines << QStringLiteral("ALTER TABLE %1 ADD %2%3;")
                             .arg(table, mssql ? QString() : QStringLiteral("COLUMN "),
                                  columnDefinition(t.after->info, *c, dialect, !sqlite));
                if (sqlite && isUnique(t.after->info, c->name))          // SQLite can't ADD COLUMN ... UNIQUE
                    lines << QStringLiteral("CREATE UNIQUE INDEX %1 ON %2 (%3);")
                                 .arg(quoteOne(constraintName(QStringLiteral("ux"), t.after->info.name, { c->name }), dialect),
                                      table, quoteOne(c->name, dialect));
            }
            for (const ColumnChange &c : t.changedColumns) {
                if (!(c.type || c.nullable || c.def))
                    continue;
                const QString col = quoteOne(c.after->name, dialect);
                if (pg) {
                    if (c.type)
                        lines << QStringLiteral("ALTER TABLE %1 ALTER COLUMN %2 TYPE %3 USING %2::%3;").arg(table, col, c.after->type);
                    if (c.nullable)
                        lines << QStringLiteral("ALTER TABLE %1 ALTER COLUMN %2 %3 NOT NULL;")
                                     .arg(table, col, c.after->nullable ? QStringLiteral("DROP") : QStringLiteral("SET"));
                    if (c.def)
                        lines << (defaultOf(*c.after).isEmpty()
                                      ? QStringLiteral("ALTER TABLE %1 ALTER COLUMN %2 DROP DEFAULT;").arg(table, col)
                                      : QStringLiteral("ALTER TABLE %1 ALTER COLUMN %2 SET DEFAULT %3;").arg(table, col, defaultOf(*c.after)));
                } else if (mysql) {
                    lines << QStringLiteral("ALTER TABLE %1 MODIFY COLUMN %2;").arg(table, columnDefinition(t.after->info, *c.after, dialect, false));
                } else if (mssql) {
                    if (c.type || c.nullable)
                        lines << QStringLiteral("ALTER TABLE %1 ALTER COLUMN %2 %3 %4;")
                                     .arg(table, col, c.after->type, c.after->nullable ? QStringLiteral("NULL") : QStringLiteral("NOT NULL"));
                    if (c.def)
                        lines << QStringLiteral("-- %1.%2: SQL Server keeps defaults as named constraints; drop the old one, then:\n"
                                                "ALTER TABLE %3 ADD DEFAULT %4 FOR %5;")
                                     .arg(t.after->info.name, c.after->name, table,
                                          defaultOf(*c.after).isEmpty() ? QStringLiteral("NULL") : defaultOf(*c.after), col);
                }
            }
            if (t.keyChanged) {
                if (pg)
                    lines << QStringLiteral("ALTER TABLE %1 DROP CONSTRAINT %2;").arg(table, quoteOne(bareName(t.before->name) + QStringLiteral("_pkey"), dialect));
                else if (mysql)
                    lines << QStringLiteral("ALTER TABLE %1 DROP PRIMARY KEY;").arg(table);
                else if (mssql)
                    lines << QStringLiteral("-- Drop %1's primary key constraint first (its name is in sys.key_constraints).").arg(t.after->info.name);
                if (!t.after->info.primaryKey.isEmpty())
                    lines << QStringLiteral("ALTER TABLE %1 ADD PRIMARY KEY (%2);").arg(table, qlist(t.after->info.primaryKey, dialect));
            }
            for (const QiForeignKeyInfo &fk : t.addedKeys)
                lines << QStringLiteral("ALTER TABLE %1 ADD CONSTRAINT %2 %3;")
                             .arg(table, quoteOne(constraintName(QStringLiteral("fk"), t.after->info.name, fk.columns), dialect),
                                  fkClause(fk, dialect));
            for (int i = 0; i < t.droppedUnique.size(); ++i) {
                const QiIndexInfo &index = t.droppedUnique.at(i);
                if (sqlite || !index.implicit)
                    lines << (mysql || mssql ? QStringLiteral("DROP INDEX %1 ON %2;").arg(quoteOne(index.name, dialect), table)
                                             : QStringLiteral("DROP INDEX %1;").arg(quoteOne(index.name, dialect)));
                else if (mysql)
                    lines << QStringLiteral("ALTER TABLE %1 DROP INDEX %2;").arg(table, quoteOne(index.name, dialect));
                else
                    lines << QStringLiteral("ALTER TABLE %1 DROP CONSTRAINT %2;").arg(table, quoteOne(index.name, dialect));
            }
            for (const QString &c : t.addedUnique)
                lines << QStringLiteral("CREATE UNIQUE INDEX %1 ON %2 (%3);")
                             .arg(quoteOne(constraintName(QStringLiteral("ux"), t.after->info.name, { c }), dialect), table, quoteOne(c, dialect));
        }
        if (!lines.isEmpty()) {
            section(t.after->info.name);
            out << lines;
        }
    }

    if (sqlite || pg || mssql)
        out << QStringLiteral("\nCOMMIT;");
    if (rebuilds)
        out << QStringLiteral("PRAGMA foreign_keys = ON;");
    return out.join(QLatin1Char('\n')).trimmed() + QLatin1Char('\n');
}

QStringList Migration::changedTables(const QVector<QiTableInfo> &original, const QVector<DesignTable> &design)
{
    QStringList out;
    for (const TableDiff &t : diff(original, design).tables)
        out << t.after->info.name;
    return out;
}

QStringList Migration::changes(const QVector<QiTableInfo> &original, const QVector<DesignTable> &design)
{
    const Diff d = diff(original, design);
    QStringList out;
    for (const DesignTable *t : d.createdTables)
        out << QStringLiteral("Create table %1").arg(t->info.name);
    for (const QiTableInfo *t : d.droppedTables)
        out << QStringLiteral("Drop table %1").arg(t->name);
    for (const TableDiff &t : d.tables) {
        const QString name = t.after->info.name;
        if (t.renamed)
            out << QStringLiteral("Rename table %1 → %2").arg(t.before->name, name);
        for (const QiColumnInfo *c : t.addedColumns)
            out << QStringLiteral("Add column %1.%2").arg(name, c->name);
        for (const QString &c : t.droppedColumns)
            out << QStringLiteral("Drop column %1.%2").arg(name, c);
        for (const ColumnChange &c : t.changedColumns) {
            if (c.renamed)
                out << QStringLiteral("Rename column %1.%2 → %3").arg(name, c.before->name, c.after->name);
            QStringList what;
            if (c.type)
                what << QStringLiteral("type %1 → %2").arg(c.before->type, c.after->type);
            if (c.nullable)
                what << (c.after->nullable ? QStringLiteral("allow NULL") : QStringLiteral("NOT NULL"));
            if (c.def)
                what << (defaultOf(*c.after).isEmpty() ? QStringLiteral("no default")
                                                       : QStringLiteral("default %1").arg(defaultOf(*c.after)));
            if (!what.isEmpty())
                out << QStringLiteral("Change %1.%2: %3").arg(name, c.after->name, what.join(QStringLiteral(", ")));
        }
        if (t.keyChanged)
            out << QStringLiteral("Primary key of %1 → (%2)").arg(name, t.after->info.primaryKey.join(QStringLiteral(", ")));
        for (const QiForeignKeyInfo &fk : t.droppedKeys)
            out << QStringLiteral("Remove reference %1.%2 → %3").arg(name, fk.columns.join(QStringLiteral(", ")), fk.refTable);
        for (const QiForeignKeyInfo &fk : t.addedKeys)
            out << QStringLiteral("Add reference %1.%2 → %3").arg(name, fk.columns.join(QStringLiteral(", ")), fk.refTable);
        for (const QString &c : t.addedUnique)
            out << QStringLiteral("Make %1.%2 unique").arg(name, c);
        for (const QString &c : t.droppedUniqueColumns)
            out << QStringLiteral("%1.%2 no longer unique").arg(name, c);
    }
    return out;
}

