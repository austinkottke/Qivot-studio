const QSet<QString> &reserved()
{
    static const QSet<QString> words = [] {
        QSet<QString> s;
        for (const char *w : { "all", "and", "as", "asc", "by", "case", "check", "column", "constraint", "create",
                               "default", "delete", "desc", "distinct", "drop", "else", "end", "from", "group",
                               "having", "in", "index", "insert", "into", "is", "join", "key", "limit", "not",
                               "null", "offset", "on", "or", "order", "primary", "references", "select", "set",
                               "table", "then", "to", "union", "unique", "update", "user", "values", "when",
                               "where", "with" })
            s.insert(QString::fromLatin1(w));
        return s;
    }();
    return words;
}

QString quoteOne(const QString &id, const QString &dialect)
{
    static const QRegularExpression lower(QStringLiteral("^[a-z_][a-z0-9_]*$"));
    static const QRegularExpression any(QStringLiteral("^[A-Za-z_][A-Za-z0-9_]*$"));
    const bool bare = (dialect == QLatin1String("postgres") ? lower : any).match(id).hasMatch()
                   && !reserved().contains(id.toLower());
    if (bare)
        return id;
    if (dialect == QLatin1String("mysql"))
        return QLatin1Char('`') + QString(id).replace(QLatin1Char('`'), QLatin1String("``")) + QLatin1Char('`');
    if (dialect == QLatin1String("sqlserver"))
        return QLatin1Char('[') + QString(id).replace(QLatin1Char(']'), QLatin1String("]]")) + QLatin1Char(']');
    return QLatin1Char('"') + QString(id).replace(QLatin1Char('"'), QLatin1String("\"\"")) + QLatin1Char('"');
}

// A table name, schema-qualified ones ("sales.orders") quoted part by part.
QString qt(const QString &name, const QString &dialect)
{
    const int dot = name.indexOf(QLatin1Char('.'));
    return dot > 0 ? quoteOne(name.left(dot), dialect) + QLatin1Char('.') + quoteOne(name.mid(dot + 1), dialect)
                   : quoteOne(name, dialect);
}

QString qlist(const QStringList &names, const QString &dialect)
{
    QStringList out;
    for (const QString &n : names)
        out << quoteOne(n, dialect);
    return out.join(QStringLiteral(", "));
}

QString bareName(const QString &table)
{
    const int dot = table.indexOf(QLatin1Char('.'));
    return dot > 0 ? table.mid(dot + 1) : table;
}

bool isUnique(const QiTableInfo &t, const QString &column)
{
    for (const QiIndexInfo &i : t.indexes)
        if (i.unique && i.columns == QStringList{ column })
            return true;
    return false;
}

int columnIndex(const QiTableInfo &t, const QString &name)
{
    for (int i = 0; i < t.columns.size(); ++i)
        if (t.columns.at(i).name == name)
            return i;
    return -1;
}

QString defaultOf(const QiColumnInfo &c)
{
    return c.defaultValue.isNull() ? QString() : c.defaultValue.toString().trimmed();
}

QString columnDefinition(const QiTableInfo &t, const QiColumnInfo &c, const QString &dialect, bool withUnique)
{
    QString def = quoteOne(c.name, dialect) + QLatin1Char(' ');
    const bool soleKey = t.primaryKey == QStringList{ c.name };
    const QString type = c.type.trimmed().isEmpty() ? QStringLiteral("TEXT") : c.type.trimmed();
    if (soleKey && c.autoIncrement) {
        if (dialect == QLatin1String("sqlite"))
            return def + QStringLiteral("INTEGER PRIMARY KEY AUTOINCREMENT");
        if (dialect == QLatin1String("postgres"))
            return def + (type.contains(QLatin1String("serial"), Qt::CaseInsensitive)
                              ? type + QStringLiteral(" PRIMARY KEY")
                              : type + QStringLiteral(" GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"));
        if (dialect == QLatin1String("mysql"))
            return def + type + QStringLiteral(" NOT NULL AUTO_INCREMENT PRIMARY KEY");
        if (dialect == QLatin1String("sqlserver"))
            return def + type + QStringLiteral(" IDENTITY(1,1) PRIMARY KEY");
    }
    def += type;
    if (soleKey)
        def += QStringLiteral(" PRIMARY KEY");
    if (!c.nullable && !soleKey)
        def += QStringLiteral(" NOT NULL");
    const QString d = defaultOf(c);
    if (!d.isEmpty())
        def += QStringLiteral(" DEFAULT ") + d;
    if (withUnique && !soleKey && isUnique(t, c.name))
        def += QStringLiteral(" UNIQUE");
    return def;
}

QString fkClause(const QiForeignKeyInfo &fk, const QString &dialect)
{
    QString s = QStringLiteral("FOREIGN KEY (%1) REFERENCES %2 (%3)")
                    .arg(qlist(fk.columns, dialect), qt(fk.refTable, dialect), qlist(fk.refColumns, dialect));
    const QString del = fk.onDelete.toUpper();
    if (!del.isEmpty() && del != QLatin1String("NO ACTION") && !(dialect == QLatin1String("sqlserver") && del == QLatin1String("RESTRICT")))
        s += QStringLiteral(" ON DELETE ") + del;
    return s;
}

QString fkSignature(const QiForeignKeyInfo &fk)
{
    const QString del = fk.onDelete.toUpper() == QLatin1String("RESTRICT") ? QStringLiteral("NO ACTION") : fk.onDelete.toUpper();
    return fk.columns.join(QLatin1Char(',')) + QLatin1String("->") + fk.refTable + QLatin1Char('(')
         + fk.refColumns.join(QLatin1Char(',')) + QLatin1String(") ") + (del.isEmpty() ? QStringLiteral("NO ACTION") : del);
}

// Everything that differs between the database and the design.
struct ColumnChange {
    const QiColumnInfo *before = nullptr;
    const QiColumnInfo *after = nullptr;
    bool renamed = false, type = false, nullable = false, def = false;
    bool any() const { return renamed || type || nullable || def; }
};

struct TableDiff {
    const QiTableInfo *before = nullptr;
    const DesignTable *after = nullptr;
    bool renamed = false;
    QStringList droppedColumns;                  // original names
    QVector<const QiColumnInfo *> addedColumns;
    QVector<ColumnChange> changedColumns;
    bool keyChanged = false;
    QVector<QiForeignKeyInfo> droppedKeys;       // as in the database
    QVector<QiForeignKeyInfo> addedKeys;         // as in the design
    QStringList addedUnique;                     // design column names
    QVector<QiIndexInfo> droppedUnique;          // as in the database
    QStringList droppedUniqueColumns;            // their columns' names in the design (or original if dropped)

    bool changed() const
    {
        return renamed || !droppedColumns.isEmpty() || !addedColumns.isEmpty() || !changedColumns.isEmpty()
            || keyChanged || !droppedKeys.isEmpty() || !addedKeys.isEmpty() || !addedUnique.isEmpty()
            || !droppedUnique.isEmpty();
    }
    // SQLite can rename, add a plain column and add a unique index; anything else is a rebuild.
    bool sqliteNeedsRebuild() const
    {
        if (!droppedColumns.isEmpty() || keyChanged || !droppedKeys.isEmpty() || !addedKeys.isEmpty())
            return true;
        for (const ColumnChange &c : changedColumns)
            if (c.type || c.nullable || c.def)
                return true;
        for (const QiColumnInfo *c : addedColumns)
            if ((!c->nullable && defaultOf(*c).isEmpty()) || after->info.primaryKey.contains(c->name))
                return true;
        for (const QiIndexInfo &i : droppedUnique)
            if (i.implicit)
                return true;
        return false;
    }
};

struct Diff {
    QVector<const QiTableInfo *> droppedTables;
    QVector<const DesignTable *> createdTables;
    QVector<TableDiff> tables;                  // the ones that exist on both sides
};

Diff diff(const QVector<QiTableInfo> &original, const QVector<DesignTable> &design)
{
    Diff d;
    QHash<QString, const QiTableInfo *> byName;
    for (const QiTableInfo &t : original)
        byName.insert(t.name, &t);

    // Table and column renames, to read the database's keys in the design's names.
    QHash<QString, QString> tableName;                       // original -> design
    QHash<QString, QHash<QString, QString>> columnName;      // original table -> original column -> design column
    QSet<QString> kept;
    for (const DesignTable &t : design) {
        if (t.origin.isEmpty() || !byName.contains(t.origin)) {
            d.createdTables << &t;
            continue;
        }
        kept.insert(t.origin);
        tableName.insert(t.origin, t.info.name);
        for (int i = 0; i < t.info.columns.size(); ++i)
            if (!t.columnOrigins.value(i).isEmpty())
                columnName[t.origin].insert(t.columnOrigins.at(i), t.info.columns.at(i).name);
    }
    for (const QiTableInfo &t : original)
        if (!kept.contains(t.name) && t.kind == QiTableInfo::Table)
            d.droppedTables << &t;

    auto mapKey = [&](const QiTableInfo &owner, const QiForeignKeyInfo &fk, bool *ok) {
        QiForeignKeyInfo m = fk;
        *ok = tableName.contains(fk.refTable);
        m.refTable = tableName.value(fk.refTable);
        m.columns.clear();
        m.refColumns.clear();
        for (const QString &c : fk.columns) {
            *ok = *ok && columnName[owner.name].contains(c);
            m.columns << columnName[owner.name].value(c);
        }
        for (const QString &c : fk.refColumns) {
            *ok = *ok && columnName[fk.refTable].contains(c);
            m.refColumns << columnName[fk.refTable].value(c);
        }
        return m;
    };

    for (const DesignTable &t : design) {
        if (t.origin.isEmpty() || !byName.contains(t.origin))
            continue;
        TableDiff td;
        td.before = byName.value(t.origin);
        td.after = &t;
        td.renamed = t.info.name != t.origin;
        const QHash<QString, QString> &cols = columnName[t.origin];

        QSet<QString> keptColumns;
        for (int i = 0; i < t.info.columns.size(); ++i) {
            const QiColumnInfo &c = t.info.columns.at(i);
            const QString origin = t.columnOrigins.value(i);
            const QiColumnInfo *before = origin.isEmpty() ? nullptr : td.before->column(origin);
            if (!before) {
                td.addedColumns << &c;
                continue;
            }
            keptColumns.insert(origin);
            ColumnChange cc;
            cc.before = before;
            cc.after = &c;
            cc.renamed = c.name != before->name;
            cc.type = c.type.trimmed().compare(before->type.trimmed(), Qt::CaseInsensitive) != 0;
            cc.nullable = c.nullable != before->nullable && !t.info.primaryKey.contains(c.name);
            cc.def = defaultOf(c) != defaultOf(*before) && !c.autoIncrement;
            if (cc.any())
                td.changedColumns << cc;
        }
        for (const QiColumnInfo &c : td.before->columns)
            if (!keptColumns.contains(c.name))
                td.droppedColumns << c.name;

        QStringList keyBefore;
        for (const QString &c : td.before->primaryKey)
            keyBefore << cols.value(c, QStringLiteral("\x01"));
        td.keyChanged = keyBefore != t.info.primaryKey;

        QSet<QString> afterKeys;
        for (const QiForeignKeyInfo &fk : t.info.foreignKeys)
            afterKeys.insert(fkSignature(fk));
        QSet<QString> beforeKeys;
        for (const QiForeignKeyInfo &fk : td.before->foreignKeys) {
            bool ok = false;
            const QiForeignKeyInfo mapped = mapKey(*td.before, fk, &ok);
            if (ok)
                beforeKeys.insert(fkSignature(mapped));
            if (!ok || !afterKeys.contains(fkSignature(mapped)))
                td.droppedKeys << fk;
        }
        for (const QiForeignKeyInfo &fk : t.info.foreignKeys)
            if (!beforeKeys.contains(fkSignature(fk)))
                td.addedKeys << fk;

        // Unique columns (single-column unique indexes and constraints).
        for (const QiIndexInfo &i : td.before->indexes) {
            if (!i.unique || i.columns.size() != 1 || td.before->primaryKey == i.columns)
                continue;
            const QString now = cols.value(i.columns.first());
            if (now.isEmpty() || !isUnique(t.info, now)) {
                td.droppedUnique << i;
                td.droppedUniqueColumns << (now.isEmpty() ? i.columns.first() : now);
            }
        }
        for (int k = 0; k < t.info.columns.size(); ++k) {
            const QiColumnInfo &c = t.info.columns.at(k);
            const QString origin = t.columnOrigins.value(k);
            if (origin.isEmpty() || !isUnique(t.info, c.name) || t.info.primaryKey == QStringList{ c.name })
                continue;                       // new columns carry their own UNIQUE
            bool before = false;
            for (const QiIndexInfo &i : td.before->indexes)
                before = before || (i.unique && i.columns == QStringList{ origin });
            if (!before)
                td.addedUnique << c.name;
        }
        if (td.changed())
            d.tables << td;
    }
    return d;
}

// New tables in an order where each one's references already exist.
QVector<const DesignTable *> creationOrder(const QVector<const DesignTable *> &created)
{
    QVector<const DesignTable *> out, pending = created;
    QSet<QString> pendingNames;
    for (const DesignTable *t : created)
        pendingNames.insert(t->info.name);
    while (!pending.isEmpty()) {
        int pick = 0;
        for (int i = 0; i < pending.size(); ++i) {
            bool ready = true;
            for (const QiForeignKeyInfo &fk : pending[i]->info.foreignKeys)
                ready = ready && (fk.refTable == pending[i]->info.name || !pendingNames.contains(fk.refTable));
            if (ready) { pick = i; break; }
        }
        pendingNames.remove(pending[pick]->info.name);
        out << pending.takeAt(pick);
    }
    return out;
}

QString constraintName(const QString &prefix, const QString &table, const QStringList &columns)
{
    return prefix + QLatin1Char('_') + bareName(table) + QLatin1Char('_') + columns.join(QLatin1Char('_'));
}

