QVariantMap SchemaDesign::diagram() const
{
    // The cards say which tables are new or edited.
    QVariantMap d = DiagramData::build(infos(), {});
    const QStringList changed = Migration::changedTables(m_original, m_tables);
    QVariantList tables = d.value(QStringLiteral("tables")).toList();
    for (QVariant &v : tables) {
        QVariantMap t = v.toMap();
        const DesignTable *dt = find(t.value(QStringLiteral("name")).toString());
        QStringList errors;
        for (const QVariant &v : problemsFor(t.value(QStringLiteral("name")).toString())) {
            const QVariantMap p = v.toMap();
            if (p.value(QStringLiteral("severity")).toString() == QLatin1String("error"))
                errors << (p.value(QStringLiteral("column")).toString().isEmpty()
                               ? p.value(QStringLiteral("message")).toString()
                               : p.value(QStringLiteral("column")).toString() + QStringLiteral(": ")
                                     + p.value(QStringLiteral("message")).toString());
        }
        const bool broken = !errors.isEmpty();
        t.insert(QStringLiteral("errors"), errors);
        t.insert(QStringLiteral("status"), broken ? QStringLiteral("error")
                                         : dt && dt->origin.isEmpty() ? QStringLiteral("new")
                                         : changed.contains(t.value(QStringLiteral("name")).toString()) ? QStringLiteral("changed")
                                         : QString());
        v = t;
    }
    d.insert(QStringLiteral("tables"), tables);
    return d;
}

QVariantMap SchemaDesign::cppModel(const QString &table) const
{
    const CodeGen::Model m = CodeGen(infos(), m_dialect).model(table);
    if (!m.isValid())
        return {};
    QVariantList warnings;
    for (const CodeGen::Warning &w : m.warnings)
        warnings << QVariantMap{ { QStringLiteral("column"), w.column }, { QStringLiteral("message"), w.message } };
    return { { QStringLiteral("className"), m.className },
             { QStringLiteral("code"), m.code },
             { QStringLiteral("warnings"), warnings } };
}

QString SchemaDesign::cppHeader() const
{
    return CodeGen(infos(), m_dialect).header();
}

QString SchemaDesign::applyToCopy()
{
    if (m_dialect != QLatin1String("sqlite") || !m_session || m_session->filePath().isEmpty()) {
        setError(tr("Applying to a copy works for SQLite files; copy the SQL for a server."));
        return QString();
    }
    const QFileInfo source(m_session->filePath());
    QString target;
    for (int n = 1; target.isEmpty() || QFileInfo::exists(target); ++n)
        target = source.dir().filePath(QStringLiteral("%1-designed%2.%3")
                                           .arg(source.completeBaseName(), n > 1 ? QString::number(n) : QString(),
                                                source.suffix().isEmpty() ? QStringLiteral("db") : source.suffix()));
    if (!QFile::copy(source.absoluteFilePath(), target)) {
        setError(tr("Couldn't copy %1.").arg(source.fileName()));
        return QString();
    }
    const QString script = migration();
    const QString connection = QStringLiteral("design-") + QUuid::createUuid().toString(QUuid::WithoutBraces);
    QString failure;
    {
        QSqlDatabase db = QSqlDatabase::addDatabase(QStringLiteral("QSQLITE"), connection);
        db.setDatabaseName(target);
        if (!db.open()) {
            failure = db.lastError().text();
        } else {
            // One statement at a time (QSqlQuery runs one); comments dropped first.
            QString text;
            for (const QString &line : script.split(QLatin1Char('\n')))
                if (!line.trimmed().startsWith(QLatin1String("--")))
                    text += line + QLatin1Char('\n');
            QSqlQuery q(db);
            for (const QString &statement : text.split(QLatin1Char(';'))) {
                if (statement.trimmed().isEmpty())
                    continue;
                if (!q.exec(statement)) {
                    failure = QStringLiteral("%1\n%2").arg(q.lastError().text(), statement.trimmed());
                    q.exec(QStringLiteral("ROLLBACK"));
                    break;
                }
            }
            db.close();
        }
    }
    QSqlDatabase::removeDatabase(connection);
    if (!failure.isEmpty()) {
        QFile::remove(target);
        setError(tr("The migration failed on the copy: %1").arg(failure));
        return QString();
    }
    setError(QString());
    return target;
}
