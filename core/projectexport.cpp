QString databaseHeader(const QVariantMap &s)
{
    const QString type = s.value(QStringLiteral("type")).toString();
    QString body;
    if (type == QLatin1String("sqlite")) {
        body = fill(QStringLiteral(
            "    QSqlDatabase db = QSqlDatabase::addDatabase(QStringLiteral(\"QSQLITE\"));\n"
            "    db.setDatabaseName(qEnvironmentVariable(\"QIVOT_DB\", QStringLiteral(@PATH@)));\n"),
            { { QStringLiteral("PATH"), cString(s.value(QStringLiteral("path")).toString()) } });
    } else {
        const QString driver = s.value(QStringLiteral("driver")).toString();
        QMap<QString, QString> v = {
            { QStringLiteral("HOST"), cString(s.value(QStringLiteral("host")).toString()) },
            { QStringLiteral("PORT"), cString(s.value(QStringLiteral("port")).toString()) },
            { QStringLiteral("DB"), cString(s.value(QStringLiteral("database")).toString()) },
            { QStringLiteral("USER"), cString(s.value(QStringLiteral("user")).toString()) },
            { QStringLiteral("DRIVER"), cString(driver) },
            { QStringLiteral("ODBC"), cString(s.value(QStringLiteral("odbcDriver")).toString()) },
        };
        body = QStringLiteral(
            "    const QString host = qEnvironmentVariable(\"QIVOT_DB_HOST\", QStringLiteral(@HOST@));\n"
            "    const int port = qEnvironmentVariable(\"QIVOT_DB_PORT\", QStringLiteral(@PORT@)).toInt();\n"
            "    const QString name = qEnvironmentVariable(\"QIVOT_DB\", QStringLiteral(@DB@));\n"
            "    const QString user = qEnvironmentVariable(\"QIVOT_DB_USER\", QStringLiteral(@USER@));\n"
            "    const QString password = qEnvironmentVariable(\"QIVOT_DB_PASSWORD\");\n\n");
        if (driver == QLatin1String("QODBC")) {
            body += QStringLiteral(
                "    // ODBC takes one connection string; {braces} quote each value.\n"
                "    auto braced = [](QString v) { return QLatin1Char('{') + v.replace(QLatin1Char('}'), QLatin1String(\"}}\")) + QLatin1Char('}'); };\n"
                "    QSqlDatabase db = QSqlDatabase::addDatabase(QStringLiteral(\"QODBC\"));\n"
                "    db.setDatabaseName(QStringLiteral(\"Driver={%1};Server=%2,%3;Database=%4;Uid=%5;Pwd=%6;TrustServerCertificate=yes;\")\n"
                "                           .arg(QStringLiteral(@ODBC@), host).arg(port)\n"
                "                           .arg(braced(name), braced(user), braced(password)));\n");
        } else {
            if (driver == QLatin1String("QMYSQL") || driver == QLatin1String("QMARIADB"))
                body += QStringLiteral(
                    "    // Qt names its MySQL driver QMARIADB in some builds.\n"
                    "    const QString driver = QSqlDatabase::isDriverAvailable(QStringLiteral(\"QMYSQL\"))\n"
                    "                         ? QStringLiteral(\"QMYSQL\") : QStringLiteral(\"QMARIADB\");\n"
                    "    QSqlDatabase db = QSqlDatabase::addDatabase(driver);\n");
            else
                body += QStringLiteral("    QSqlDatabase db = QSqlDatabase::addDatabase(QStringLiteral(@DRIVER@));\n");
            body += QStringLiteral(
                "    db.setHostName(host);\n"
                "    db.setPort(port);\n"
                "    db.setDatabaseName(name);\n"
                "    db.setUserName(user);\n"
                "    db.setPassword(password);\n");
        }
        body = fill(body, v);
    }
    return QStringLiteral(
        "// Opens the database the project was generated from; see README.md to point it elsewhere.\n"
        "#ifndef DATABASE_H\n#define DATABASE_H\n\n"
        "#include <QDebug>\n#include <QSqlDatabase>\n#include <QSqlError>\n#include <qivot.hpp>\n\n"
        "/// Connects Qt to the database and opens a Qivot connection on it.\n"
        "inline bool openDatabase(QiConnection &connection)\n{\n")
        + body
        + QStringLiteral(
        "    if (!db.open()) {\n"
        "        qWarning().noquote() << \"Can't open the database:\" << db.lastError().text();\n"
        "        return false;\n"
        "    }\n"
        "    return connection.open(db);\n}\n\n#endif // DATABASE_H\n");
}

QString environmentTable(const QVariantMap &s)
{
    if (s.value(QStringLiteral("type")).toString() == QLatin1String("sqlite"))
        return QStringLiteral("| Variable | Default |\n|----------|---------|\n| `QIVOT_DB` | `%1` |\n")
            .arg(s.value(QStringLiteral("path")).toString());
    return QStringLiteral("| Variable | Default |\n|----------|---------|\n"
                          "| `QIVOT_DB_HOST` | `%1` |\n| `QIVOT_DB_PORT` | `%2` |\n| `QIVOT_DB` | `%3` |\n"
                          "| `QIVOT_DB_USER` | `%4` |\n| `QIVOT_DB_PASSWORD` | (none: it is never written to disk) |\n")
        .arg(s.value(QStringLiteral("host")).toString(), s.value(QStringLiteral("port")).toString(),
             s.value(QStringLiteral("database")).toString(), s.value(QStringLiteral("user")).toString());
}

// The example's second half: follow one foreign key, labelled by a text field on each side.
QString followExample(const QVector<CodeGen::Model> &models, QString *summary)
{
    auto textField = [](const CodeGen::Model &m) -> QString {
        for (const CodeGen::Field &f : m.fields)
            if (f.cppType == QLatin1String("QString") && f.target.isEmpty())
                return f.name;
        return QString();
    };
    for (const CodeGen::Model &m : models) {
        const QString label = textField(m);
        if (label.isEmpty())
            continue;
        for (const CodeGen::Field &f : m.fields) {
            if (f.target.isEmpty())
                continue;
            const CodeGen::Model *parent = nullptr;
            for (const CodeGen::Model &p : models)
                if (p.className == f.target)
                    parent = &p;
            const QString parentLabel = parent ? textField(*parent) : QString();
            if (parentLabel.isEmpty())
                continue;
            *summary = QStringLiteral(", then follows %1.%2 to %3").arg(m.className, f.name, f.target);
            return fill(QStringLiteral(
                "\n    // A QiForeignKey loads the row it points at the first time you use it.\n"
                "    qInfo().noquote() << \"\\n@CLASS@ -> @TARGET@:\";\n"
                "    QiList<@CLASS@> rows = @CLASS@::objects().limit(5).all();\n"
                "    for (int i = 0; i < rows.size(); ++i) {\n"
                "        @CLASS@ *row = rows.at(i);\n"
                "        qInfo().noquote() << \"  \" << row->@LABEL@.get().toString()\n"
                "                          << \"->\" << row->@FIELD@->@PLABEL@.get().toString();\n"
                "    }\n"),
                { { QStringLiteral("CLASS"), m.className }, { QStringLiteral("TARGET"), f.target },
                  { QStringLiteral("LABEL"), label }, { QStringLiteral("FIELD"), f.name },
                  { QStringLiteral("PLABEL"), parentLabel } });
        }
    }
    return QString();
}

