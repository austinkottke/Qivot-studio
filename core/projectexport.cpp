ProjectExport::ProjectExport(QObject *parent)
    : QObject(parent)
    , m_directory(defaultDirectory())
{
}

void ProjectExport::setSession(DatabaseSession *session)
{
    if (session == m_session)
        return;
    if (m_session)
        disconnect(m_session, nullptr, this, nullptr);
    m_session = session;
    if (m_session)
        connect(m_session, &DatabaseSession::openChanged, this, [this] {
            emit sessionChanged();
            regenerate();
        });
    emit sessionChanged();
    regenerate();
}

void ProjectExport::setName(const QString &name)
{
    if (name == m_name)
        return;
    m_name = name;
    emit nameChanged();
    emit pathChanged();
    regenerate();
}

void ProjectExport::setDirectory(const QString &directory)
{
    QString dir = directory;
    if (dir.startsWith(QLatin1String("file:")))
        dir = QUrl(dir).toLocalFile();
    if (dir == m_directory)
        return;
    m_directory = dir;
    emit directoryChanged();
    emit pathChanged();
}

QString ProjectExport::projectPath() const
{
    return m_name.trimmed().isEmpty() ? QString() : QDir(m_directory).filePath(m_name.trimmed());
}

QString ProjectExport::displayPath() const
{
    const QString path = projectPath();
    const QString home = QDir::homePath();
    return path.startsWith(home + QLatin1Char('/')) ? QLatin1Char('~') + path.mid(home.size()) : path;
}

bool ProjectExport::exists() const
{
    const QString path = projectPath();
    return !path.isEmpty() && QFileInfo::exists(QDir(path).filePath(QStringLiteral("CMakeLists.txt")));
}

QString ProjectExport::suggestedName() const
{
    if (!m_session || !m_session->isOpen())
        return QString();
    QString base = QFileInfo(m_session->displayName()).completeBaseName();
    if (base.isEmpty())
        base = m_session->displayName();
    QString name;
    bool upper = true;
    for (const QChar c : base) {
        if (!c.isLetterOrNumber()) {
            upper = true;
            continue;
        }
        name += upper ? c.toUpper() : c;
        upper = false;
    }
    return name.isEmpty() ? QStringLiteral("Models") : name;
}

QString ProjectExport::defaultDirectory()
{
    return QDir(QStandardPaths::writableLocation(QStandardPaths::DocumentsLocation))
        .filePath(QStringLiteral("Qivot Projects"));
}

void ProjectExport::regenerate()
{
    m_files.clear();
    if (m_session && m_session->isOpen() && !m_name.trimmed().isEmpty())
        m_files = generate(*m_session, m_name.trimmed());
    emit filesChanged();
}

void ProjectExport::setError(const QString &error)
{
    if (error == m_error)
        return;
    m_error = error;
    emit errorChanged();
}

bool ProjectExport::write()
{
    const QString root = projectPath();
    if (root.isEmpty() || m_files.isEmpty()) {
        setError(tr("Open a database and name the project first."));
        return false;
    }
    for (auto it = m_files.cbegin(); it != m_files.cend(); ++it) {
        const QString path = QDir(root).filePath(it.key());
        if (!QDir().mkpath(QFileInfo(path).absolutePath())) {
            setError(tr("Couldn't create %1.").arg(QFileInfo(path).absolutePath()));
            return false;
        }
        QFile file(path);
        if (!file.open(QIODevice::WriteOnly) || file.write(it.value().toUtf8()) < 0) {
            setError(tr("Couldn't write %1: %2").arg(path, file.errorString()));
            return false;
        }
    }
    setError(QString());
    emit pathChanged();
    emit written();
    return true;
}

bool ProjectExport::writeFile(const QString &file)
{
    const QString root = projectPath();
    if (root.isEmpty() || !m_files.contains(file)) {
        setError(tr("There's no generated %1.").arg(file));
        return false;
    }
    const QString path = QDir(root).filePath(file);
    QDir().mkpath(QFileInfo(path).absolutePath());
    QFile out(path);
    if (!out.open(QIODevice::WriteOnly) || out.write(m_files.value(file).toUtf8()) < 0) {
        setError(tr("Couldn't write %1: %2").arg(path, out.errorString()));
        return false;
    }
    setError(QString());
    return true;
}

QMap<QString, QString> ProjectExport::generate(const DatabaseSession &session, const QString &name)
{
    const CodeGen gen(session.tableInfos(), session.dialect());
    const QVector<CodeGen::Model> models = gen.models();
    const QVariantMap settings = session.connectionSettings();
    const QString source = settings.value(QStringLiteral("type")).toString() == QLatin1String("sqlite")
                         ? session.displayName()
                         : QStringLiteral("%1 on %2").arg(session.displayName(), session.location());

    QStringList classes;
    for (const CodeGen::Model &m : models)
        classes << m.className;

    const QString ident = identifier(name);
    QMap<QString, QString> files;

    QStringList modelLines;
    for (const QString &c : classes)
        modelLines << QStringLiteral("    ") + c;
    files.insert(QStringLiteral("CMakeLists.txt"),
                 fill(QString::fromUtf8(CMakeTemplate),
                      { { QStringLiteral("NAME"), name }, { QStringLiteral("SOURCE"), source },
                        { QStringLiteral("IDENT"), ident }, { QStringLiteral("TARGET"), ident.toLower() },
                        { QStringLiteral("MODELS"), modelLines.join(QLatin1Char('\n')) } }));

    files.insert(QStringLiteral("README.md"),
                 fill(QString::fromUtf8(ReadmeTemplate),
                      { { QStringLiteral("NAME"), name }, { QStringLiteral("SOURCE"), source },
                        { QStringLiteral("COUNT"), QString::number(models.size()) },
                        { QStringLiteral("ENV"), environmentTable(settings) } }));

    // Qivot itself: the single header Studio was built with, so the project
    // builds as it is, offline, against the same Qivot.
    for (const char *f : { "qivot.hpp", "qivot.cpp", "LICENSE.txt", "NOTICE.txt" })
        files.insert(QStringLiteral("third_party/qivot/") + QLatin1String(f), qivotFile(QLatin1String(f)));

    files.insert(QStringLiteral("src/models.h"), gen.header());
    files.insert(QStringLiteral("src/database.h"), databaseHeader(settings));

    // main.cpp: a row count per model, then one foreign key followed.
    int width = 0;
    for (const QString &c : classes)
        width = qMax(width, int(c.size()));
    QString counts;
    for (const QString &c : classes)
        counts += QStringLiteral("    qInfo().noquote() << QStringLiteral(\"  ") + c.leftJustified(width)
                + QStringLiteral(" %1\").arg(") + c + QStringLiteral("::objects().count());\n");
    QString follows;
    const QString example = followExample(models, &follows);
    files.insert(QStringLiteral("src/main.cpp"),
                 fill(QString::fromUtf8(MainTemplate),
                      { { QStringLiteral("NAME"), name }, { QStringLiteral("SOURCE"), source },
                        { QStringLiteral("FOLLOWS"), follows }, { QStringLiteral("COUNTS"), counts },
                        { QStringLiteral("EXAMPLE"), example } }));

    // tests: one slot per model, named like it so `tst_models Album` runs one.
    QString testSlots;
    for (const CodeGen::Model &m : models) {
        QStringList checks;
        for (const CodeGen::Field &f : m.fields)
            if (!f.target.isEmpty())
                checks << fill(QStringLiteral(
                    "            QVERIFY2(follows(row.@FIELD@),\n"
                    "                     qPrintable(QStringLiteral(\"@FIELD@ = %1: no @TARGET@ row has that key\")\n"
                    "                                    .arg(row.@FIELD@.get().toString())));\n"),
                    { { QStringLiteral("FIELD"), f.name }, { QStringLiteral("TARGET"), f.target } });
        testSlots += QStringLiteral("\n    void %1()\n    {\n").arg(m.className);
        if (checks.isEmpty())
            testSlots += QStringLiteral("        loadsEveryRow<::%1>([](::%1 &, qint64) {});\n").arg(m.className);
        else
            testSlots += QStringLiteral("        loadsEveryRow<::%1>([](::%1 &row, qint64 n) {\n"
                                    "            if (n >= FollowedKeys)\n                return;\n%2"
                                    "        });\n").arg(m.className, checks.join(QString()));
        testSlots += QStringLiteral("    }\n");
    }
    files.insert(QStringLiteral("tests/tst_models.cpp"),
                 fill(QString::fromUtf8(TestTemplate),
                      { { QStringLiteral("SLOTS"), testSlots },
                        { QStringLiteral("FIRST"), classes.value(0, QStringLiteral("Model")) } }));
    return files;
}
