const char *TestTemplate = R"(// One test per model: every row loads, and each foreign key finds its row.
// Run them all with ctest, or one model with: tst_models @FIRST@
#include <QtTest>
#include <QSqlError>
#include <QSqlQuery>

#include "database.h"
#include "models.h"

namespace {

constexpr qint64 MappedRows = 5000;   // rows read into a model; the rest are only counted
constexpr qint64 FollowedKeys = 25;   // rows whose foreign keys are followed

// A model's key: Qivot's built-in id, or its QiPrimary field.
template <typename T>
QVariant keyOf(T &model)
{
    QiModelMetaInfo *info = qiMetaInfo<T>();
    const QString key = info->primaryKeyName();
    return info->value(&model, key.isEmpty() ? QStringLiteral("id") : key);
}

// A foreign key must load the row it points at.
template <typename Key>
bool follows(Key &key)
{
    return key.get().isNull() || keyOf(key()).toLongLong() == key.get().toLongLong();
}

} // namespace

class TestModels : public QObject
{
    Q_)" "OBJECT" R"(

    QiConnection m_connection;

    // Reads T's whole table through Qivot. The row count must match COUNT(*),
    // and `each` checks the first MappedRows rows.
    template <typename T, typename Each>
    void loadsEveryRow(Each each)
    {
        QSqlQuery count;
        QVERIFY2(count.exec(QStringLiteral("SELECT COUNT(*) FROM ") + T::TableName()),
                 qPrintable(count.lastError().text()));
        QVERIFY(count.next());
        const qint64 expected = count.value(0).toLongLong();

        QiQuery<T> query;
        QVERIFY2(query.exec(), "Qivot's SELECT failed");
        qint64 rows = 0;
        while (query.next()) {
            if (rows < MappedRows) {
                T row;
                QVERIFY2(query.recordTo(row), qPrintable(QStringLiteral("row %1 didn't load").arg(rows + 1)));
                each(row, rows);
                if (QTest::currentTestFailed())
                    return;
            }
            ++rows;
        }
        QCOMPARE(rows, expected);
    }

private slots:
    void initTestCase() { QVERIFY(openDatabase(m_connection)); }
@SLOTS@};

QTEST_GUILESS_MAIN(TestModels)
#)" "include \"tst_models.moc\"\n";

